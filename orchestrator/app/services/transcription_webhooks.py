async def process_raw_text(raw_text: str):
    processed_text = await llm_client.chat.completions.create(
        model="qwen3.6-fp8",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Привет, вот текст: {raw_text} "},
        ],
    )

    processed_text = processed_text.choices[0].message.content

    if processed_text is None:
        processed_text = " "

    return processed_text


async def save_text_file_metadata_to_db(
    file_name: str, file_url: str, session: AsyncSession
):
    text_file_metadata = AudioProcessingResult(name=file_name, result_s3_url=file_url)

    try:
        session.add(text_file_metadata)
        await session.commit()

    except:
        await session.rollback()


async def handle_transcription_result(raw_text: str, audio_name, session: AsyncSession):
    processed_text = await process_raw_text(raw_text)

    text_file_path = await build_file_path()

    text_file_url = await build_file_url(text_file_path)

    await save_text_file_metadata_to_db(
        file_name=audio_name, file_url=text_file_url, session=session
    )

    await upload_file_to_s3(text_file_path, BytesIO(processed_text.encode()))
